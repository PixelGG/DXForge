---@param value boolean
---@return table
function Window:SetOpen(value)
    self.Open = value == true
    return self
end

--[[
    Resizes the window to an exact width and height.

    @param width number|table
        New width in pixels, or a size table in the form {width, height}.
    @param height number|nil
        New height in pixels when width is passed as a number.
    @return table
        Returns the window instance.
]]
---@param width number|DXForgeVector2
---@param height number|nil
---@return table
function Window:Resize(width, height)
    local size = type(width) == "table" and width or {width, height}
    local nextWidth = tonumber(size[1]) or self.Size[1]
    local nextHeight = tonumber(size[2]) or self.Size[2]
    self.Size[1] = math.max(self.MinSize[1], nextWidth)
    self.Size[2] = math.max(self.MinSize[2], nextHeight)
    return self
end

--[[
    Alias for Window:Resize.

    @param size table
        Size table in the form {width, height}.
    @return table
        Returns the window instance.
]]
---@param size DXForgeVector2
---@return table
function Window:SetSize(size)
    return self:Resize(size)
end

--[[
    Updates the minimum resize size for this window.

    @param size table
        Minimum size table in the form {width, height}.
    @return table
        Returns the window instance.
]]
---@param size DXForgeVector2
---@return table
function Window:SetMinSize(size)
    local nextSize = normalizeVec2(size, self.MinSize)
    self.MinSize = {math.max(420, nextSize[1]), math.max(320, nextSize[2])}
    return self:Resize(self.Size)
end

--[[
    Toggles window open state.

    @return table
        Returns the window instance.
]]
---@return table
function Window:Toggle()
    self.Open = not self.Open
    return self
end

--[[
    Raises the window above other DXForge windows.

    @return table
        Returns the window instance.
]]
---@return table
function Window:BringToFront()
    DXForge.Runtime.ZCounter = DXForge.Runtime.ZCounter + 1
    self.ZIndex = DXForge.Runtime.ZCounter
    DXForge.Runtime.ActiveWindow = self
    return self
end

function Window:contentRect()
    return self.Position[1] + 14, self.Position[2] + 76, self.Size[1] - 28, self.Size[2] - (self.Footer and 94 or 68)
end

function Window:handleInput(theme)
    if self.ToggleKey and Input.KeyPressed and Input.Key == self.ToggleKey then
        self:Toggle()
    end

    local x, y = self.Position[1], self.Position[2]
    local w, h = self.Size[1], self.Size[2]
    local id = self.Id

    if Input.ClickStarted and Input:hover(x, y, w, h) and DXForge.Runtime.InputWindow == self then
        self:BringToFront()
    end

    if DXForge.Runtime.InputWindow ~= self and not self.Dragging and not self.Resizing then
        return
    end

    if Input:clicked(id .. ":drag", x, y, w, DXForge.Config.HeaderHeight) then
        self:BringToFront()
        self.Dragging = true
        self.DragOffset = {Input.Mouse.x - x, Input.Mouse.y - y}
    end

    if self.Resizable and Input:clicked(id .. ":resize", x + w - 14, y + h - 14, 14, 14) then
        self:BringToFront()
        self.Resizing = true
    end

    if not Input.MouseDown then
        self.Dragging = false
        self.Resizing = false
    end

    if self.Dragging then
        Input:claim(id .. ":drag")
        local sw, sh = Render.screen()
        self.Position[1] = clamp(Input.Mouse.x - self.DragOffset[1], 0, sw - 60)
        self.Position[2] = clamp(Input.Mouse.y - self.DragOffset[2], 0, sh - 35)
    elseif self.Resizing then
        Input:claim(id .. ":resize")
        self:Resize(Input.Mouse.x - x, Input.Mouse.y - y)
    end
end

function Window:renderTabs(theme)
    local x, y = self.Position[1] + 14, self.Position[2] + 40
    local cursor = x
    local maxX = self.Position[1] + self.Size[1] - 14
    Render.filled({x - 3, y - 5}, {maxX, y + DXForge.Config.TabHeight + 5}, theme.SurfaceDarkColor or {9, 10, 15})
    Render.filled({x - 3, y - 5}, {maxX, y - 4}, theme.BorderSoftColor or theme.OutlineColor)
    Render.filled({x - 3, y + DXForge.Config.TabHeight + 4}, {maxX, y + DXForge.Config.TabHeight + 5}, theme.OutlineColor)

    for index, tab in ipairs(self.Tabs) do
        local tw = math.min(Render.textWidth(tab.Name) + 34, 140)
        if cursor + tw > maxX then break end
        local active = self.ActiveTab == tab
        local id = self.Id .. ":tab:" .. tostring(index)
        if Input:clicked(id, cursor, y, tw, DXForge.Config.TabHeight) then
            self.ActiveTab = tab
        end
        Input:release(id)

        local t = DXForge:Animate(id .. ":active", active and 1 or 0, 15)
        local hovered = Input:hover(cursor, y, tw, DXForge.Config.TabHeight)
        local hover = DXForge:Animate(id .. ":hover", hovered and 1 or 0, 16)
        Render.surface(cursor, y, tw, DXForge.Config.TabHeight, theme, active, hovered)
        Render.filled({cursor + 2, y + 2}, {cursor + tw - 2, y + DXForge.Config.TabHeight - 2}, blend(blend(theme.SurfaceDarkColor or theme.BackgroundColor, theme.PanelColor, t), theme.HoverColor, hover * 0.45))
        Render.filled({cursor + 4, y + 5}, {cursor + 5, y + DXForge.Config.TabHeight - 5}, active and theme.AccentColor or blend(theme.OutlineColor, theme.AccentColor, hover * 0.5))
        if active then
            Render.filled({cursor + 2, y + 2}, {cursor + tw - 2, y + 4}, theme.AccentColor)
            Render.filled({cursor + 8, y + DXForge.Config.TabHeight - 3}, {cursor + tw - 8, y + DXForge.Config.TabHeight - 1}, theme.GlowColor)
            Render.filled({cursor + 7, y + 6}, {cursor + tw - 7, y + 7}, theme.AccentDimColor or theme.AccentColor)
        end
        Render.text({cursor + 14, y + 8}, active and (theme.TextHeaderColor or theme.FontColor) or theme.TextMutedColor, Render.trimText(tab.Name, tw - 26))
        cursor = cursor + tw + 7
    end
end

function Window:renderFooter(theme)
    if not self.Footer then return end
    local x, y = self.Position[1], self.Position[2]
    local w, h = self.Size[1], self.Size[2]
    local footerY = y + h - 32
    Render.filled({x + 3, footerY - 1}, {x + w - 3, y + h - 3}, theme.HeaderDarkColor or {10, 11, 16})
    Render.filled({x + 10, footerY - 3}, {x + w - 10, footerY - 2}, theme.OutlineColor)
    Render.filled({x + 10, footerY - 2}, {x + 126, footerY - 1}, theme.AccentColor)
    Render.filled({x + 14, footerY + 10}, {x + 20, footerY + 16}, theme.AccentColor)
    Render.filled({x + 23, footerY + 12}, {x + 46, footerY + 13}, theme.AccentDimColor or theme.AccentColor)
    Render.text({x + 52, footerY + 6}, theme.TextMutedColor, "DXForge " .. DXForge.__DXFORGE_VERSION)
    local keyText = self.ToggleKey and ("Toggle: " .. self.ToggleKey) or "Ready"
    Render.text({x + w - Render.textWidth(keyText) - 14, footerY + 6}, theme.TextMutedColor, keyText)
end

function Window:renderContentScroll(theme, cx, cy, cw, ch, contentHeight)
    local maxScroll = math.max(0, (contentHeight or 0) - ch)
    self.MaxScroll = maxScroll
    self.ScrollY = clamp(self.ScrollY or 0, 0, maxScroll)

    if maxScroll <= 1 then
        self.ScrollDragging = false
        return
    end

    local trackX = cx + cw - 9
    local trackY = cy + 9
    local trackW = 5
    local trackH = ch - 18
    local thumbH = clamp((ch / math.max(contentHeight, ch)) * trackH, 34, trackH)
    local travel = math.max(1, trackH - thumbH)
    local thumbY = trackY + (self.ScrollY / maxScroll) * travel
    local id = self.Id .. ":content-scroll"

    if Input:clicked(id, trackX - 5, trackY, trackW + 10, trackH) then
        self.ScrollDragging = true
        if Input.Mouse.y >= thumbY and Input.Mouse.y <= thumbY + thumbH then
            self.ScrollDragOffset = Input.Mouse.y - thumbY
        else
            self.ScrollDragOffset = thumbH / 2
            local target = clamp(Input.Mouse.y - trackY - self.ScrollDragOffset, 0, travel)
            self.ScrollY = clamp((target / travel) * maxScroll, 0, maxScroll)
        end
    end

    if self.ScrollDragging and Input.MouseDown then
        Input:claim(id)
        local target = clamp(Input.Mouse.y - trackY - (self.ScrollDragOffset or 0), 0, travel)
        self.ScrollY = clamp((target / travel) * maxScroll, 0, maxScroll)
        thumbY = trackY + (self.ScrollY / maxScroll) * travel
    elseif self.ScrollDragging and not Input.MouseDown then
        self.ScrollDragging = false
    end
    Input:release(id)

    local hovered = Input:hover(trackX - 5, trackY, trackW + 10, trackH)
    Render.filled({trackX, trackY}, {trackX + trackW, trackY + trackH}, theme.SurfaceDarkColor or {8, 9, 13})
    Render.filled({trackX + 1, trackY + 1}, {trackX + trackW - 1, trackY + trackH - 1}, theme.BorderSoftColor or theme.OutlineColor)
    Render.filled({trackX - 1, thumbY}, {trackX + trackW + 1, thumbY + thumbH}, self.ScrollDragging and theme.GlowColor or (hovered and theme.AccentColor or theme.AccentDimColor))
    Render.filled({trackX, thumbY + 2}, {trackX + trackW, thumbY + thumbH - 2}, self.ScrollDragging and theme.AccentColor or theme.GlowColor)
end

function Window:render()
    local theme = DXForge:GetTheme(self.ThemeName)
    self:handleInput(theme)

    self.Alpha = DXForge:Animate(self.Id .. ":open", self.Open and 1 or 0, 14)
    if self.Alpha <= 0.01 then return end

    local x, y = self.Position[1], self.Position[2]
    local w, h = self.Size[1], self.Size[2]
    Render.panel(x, y, w, h, theme, true)
    Render.PushClipRect(x, y, w, h)
    Render.filled({x + 3, y + 7}, {x + w - 3, y + DXForge.Config.HeaderHeight + 5}, blend(theme.HeaderColor or theme.MainColor, theme.PanelColor, 0.28))
    Render.filled({x + 14, y + 10}, {x + 20, y + 26}, theme.AccentColor)
    Render.filled({x + 23, y + 10}, {x + 24, y + 26}, theme.GlowColor)
    Render.text({x + 34, y + 10}, theme.TextHeaderColor or theme.FontColor, Render.trimText(self.Title, w - 146))
    Render.filled({x + w - 126, y + 12}, {x + w - 18, y + 13}, theme.BorderStrongColor or {51, 53, 65})
    Render.filled({x + w - 126, y + 18}, {x + w - 58, y + 19}, theme.AccentColor)
    Render.filled({x + w - 50, y + 16}, {x + w - 18, y + 17}, theme.AccentDimColor or theme.AccentColor)

    self:renderTabs(theme)

    local cx, cy, cw, ch = self:contentRect()
    Render.innerFrame(cx - 1, cy - 1, cw + 2, ch + 2, theme)
    Render.PushClipRect(cx, cy, cw, ch)
    Render.contentTexture(cx, cy, cw, ch, theme)

    local contentHeight = 0
    if self.ActiveTab then
        contentHeight = self.ActiveTab:render(theme, cx + 14, cy + 15 - (self.ScrollY or 0), cw - 34, ch - 30)
    end
    Render.PopClipRect()

    self:renderContentScroll(theme, cx, cy, cw, ch, contentHeight + 30)

    if self.Resizable then
        Render.filled({x + w - 27, y + h - 27}, {x + w - 7, y + h - 7}, theme.SurfaceDarkColor or {9, 10, 15})
        Render.filled({x + w - 25, y + h - 25}, {x + w - 8, y + h - 24}, theme.BorderSoftColor or theme.OutlineColor)
        Render.line({x + w - 20, y + h - 8}, {x + w - 8, y + h - 20}, theme.OutlineColor)
        Render.line({x + w - 15, y + h - 8}, {x + w - 8, y + h - 15}, theme.AccentColor)
        Render.line({x + w - 10, y + h - 8}, {x + w - 8, y + h - 10}, theme.GlowColor)
    end

    self:renderFooter(theme)
    Render.PopClipRect()
end

