function DXForge.AssetLoader:getLogoSources()
    local logo = DXForge.Logo
    local sources = {}
    local seen = {}

    local function add(kind, value, ratio)
        if type(value) ~= "string" or value == "" then return end
        local key = kind .. ":" .. value
        if seen[key] then return end
        seen[key] = true
        table.insert(sources, {Kind = kind, Value = value, Ratio = ratio or logo.Ratio or self.LogoRatio})
    end

    if logo.CachePath then
        add("path", logo.CachePath, logo.Ratio)
    end

    if type(logo.LocalSources) == "table" then
        for _, source in ipairs(logo.LocalSources) do
            local ratio = logo.Ratio
            if source == "assets/DXForgeSingle.png" then ratio = 1.5 end
            if source == "assets/DXForgeBanner.png" then ratio = 3 end
            add("path", source, ratio)
        end
    elseif logo.Source then
        add("path", logo.Source, logo.Ratio)
    end

    if logo.RemoteSource then
        add("remote", logo.RemoteSource, logo.Ratio)
    end

    return sources
end

function DXForge.AssetLoader:prepareLogo()
    local logo = DXForge.Logo
    if logo.Prepared then return end
    logo.Prepared = true
    logo.LoadStartedAt = logo.LoadStartedAt or os.clock()
    logo.Status = "loading"

    if logo.RemoteSource and dx9 and dx9.Get and logo.CachePath then
        local ok, body = dxSafeCall(dx9.Get, logo.RemoteSource)
        if ok and type(body) == "string" and body ~= "" then
            logo.Downloaded = true
            if self:isPng(body) then
                if self:writeCache(logo.CachePath, body) then
                    logo.Status = "cached"
                    self:warn("Downloaded and cached startup logo at " .. tostring(logo.CachePath))
                else
                    logo.LastError = "Downloaded logo but could not write cache: " .. tostring(logo.CachePath)
                    self:warn(logo.LastError)
                end
            else
                logo.LastError = "Downloaded startup logo is not a PNG payload"
                self:warn(logo.LastError)
            end
        else
            logo.LastError = "dx9.Get failed for " .. tostring(logo.RemoteSource)
            self:warn(logo.LastError)
        end
    elseif logo.RemoteSource and not (dx9 and dx9.Get) then
        logo.LastError = "dx9.Get is not available; using local startup logo paths"
        self:warn(logo.LastError)
    end
end

function DXForge.AssetLoader:getLogoRatio()
    return DXForge.Logo.ActiveRatio or DXForge.Logo.Ratio or self.LogoRatio or 1
end

function Render.drawImageCandidate(image, x, y, w, h, color)
    if not (dx9 and dx9.DrawImage) or image == nil then return false end

    local p1 = point(x, y)
    local p2 = point(x + w, y + h)
    local size = point(w, h)
    local rgb = copyColor(color or {255, 255, 255})
    local attempts = {
        {image, p1, p2, rgb},
        {p1, p2, image, rgb},
        {image, p1, size, rgb},
        {p1, size, image, rgb},
        {p1, p2, rgb, image},
        {image, x, y, w, h},
        {x, y, w, h, image},
        {image, x, y, w, h, rgb},
        {x, y, w, h, image, rgb}
    }

    for _, args in ipairs(attempts) do
        local ok, result = dxSafeCall(dx9.DrawImage, unpack(args))
        if ok and result ~= false then return true end
    end

    return false
end

function DXForge.AssetLoader:drawLogo(x, y, w, h, color)
    local logo = DXForge.Logo
    self:prepareLogo()

    if not (dx9 and dx9.DrawImage) then
        logo.Status = "unsupported"
        logo.Failed = true
        logo.LastError = "dx9.DrawImage is not available in this DX9 runtime"
        return false, logo.Status
    end

    if logo.Loaded and logo.Asset then
        if Render.drawImageCandidate(logo.Asset, x, y, w, h, color) then
            return true, "loaded"
        end
        logo.Loaded = false
        logo.Asset = nil
        logo.Status = "retry"
    end

    for _, source in ipairs(self:getLogoSources()) do
        local key = tostring(source.Kind) .. ":" .. tostring(source.Value)
        if source.Value then
            logo.Attempts[key] = (logo.Attempts[key] or 0) + 1
            local asset = source.Value

            if source.Kind == "remote" then
                asset = source.Value
            elseif source.Kind == "path" and not self:fileExists(source.Value) then
                asset = nil
            end

            if asset and Render.drawImageCandidate(asset, x, y, w, h, color) then
                logo.Asset = asset
                logo.ActiveSource = source.Value
                logo.ActiveRatio = source.Ratio or logo.Ratio
                logo.Loaded = true
                logo.Failed = false
                logo.Status = "loaded"
                return true, logo.Status
            elseif logo.Attempts[key] == 1 then
                logo.LastError = "Could not render startup logo source: " .. tostring(source.Value)
                self:warn(logo.LastError)
            end
        end
    end

    if os.clock() - logo.LoadStartedAt >= logo.LoadTimeout then
        logo.Status = "failed"
        logo.Failed = true
        logo.LastError = logo.LastError or "No DXForge logo source could be rendered"
        self:warn(logo.LastError)
        return false, logo.Status
    end

    logo.Status = "loading"
    return false, logo.Status
end

--// Input System --------------------------------------------------------------

local Input = {
    Mouse = {x = 0, y = 0},
    LastMouse = {x = 0, y = 0},
    MouseDown = false,
    LastMouseDown = false,
    ClickStarted = false,
    ClickReleased = false,
    Key = "[None]",
    LastKey = "[None]",
    KeyPressed = false,
    Claimed = false,
    ClaimId = nil,
    ActiveId = nil,
    FocusText = nil,
    Drag = nil
}

function Input:update()
    local mouse = {x = 0, y = 0}
    if dx9 and dx9.GetMouse then
        local ok, result = dxSafeCall(dx9.GetMouse)
        if ok and type(result) == "table" then
            mouse = result
        end
    end
    self.LastMouse.x, self.LastMouse.y = self.Mouse.x, self.Mouse.y
    self.Mouse.x, self.Mouse.y = mouse.x or 0, mouse.y or 0
    self.LastMouseDown = self.MouseDown
    if dx9 and dx9.isLeftClickHeld then
        local ok, result = dxSafeCall(dx9.isLeftClickHeld)
        self.MouseDown = ok and result == true
    else
        self.MouseDown = false
    end
    self.ClickStarted = self.MouseDown and not self.LastMouseDown
    self.ClickReleased = (not self.MouseDown) and self.LastMouseDown
    self.LastKey = self.Key
    if dx9 and dx9.GetKey then
        local ok, result = dxSafeCall(dx9.GetKey)
        self.Key = ok and tostring(result or "[None]") or "[None]"
    else
        self.Key = "[None]"
    end
    self.KeyPressed = self.Key ~= "[None]" and self.Key ~= "[Unknown]" and self.Key ~= self.LastKey
    self.Claimed = false
    self.ClaimId = nil
end

function Input:hover(x, y, w, h)
    local rect = Render.ClippedRect(x, y, w, h)
    if not rect then return false end
    local mx, my = self.Mouse.x, self.Mouse.y
    return mx >= rect.x and my >= rect.y and mx <= rect.x + rect.w and my <= rect.y + rect.h
end

function Input:canClaim(id)
    return not self.Claimed or self.ClaimId == id or self.ActiveId == id
end

function Input:claim(id)
    if self:canClaim(id) then
        self.Claimed = true
        self.ClaimId = id
        return true
    end
    return false
end

function Input:clicked(id, x, y, w, h)
    if self.ClickStarted and self:hover(x, y, w, h) and self:claim(id) then
        self.ActiveId = id
        return true
    end
    return false
end

function Input:release(id)
    if self.ClickReleased and self.ActiveId == id then
        self.ActiveId = nil
        return true
    end
    return false
end

DXForge.Input = Input

--// Animation System ----------------------------------------------------------

--[[
    Interpolates a named animation value toward a target.

    @param id string
        Stable animation id.
    @param target number
        Target value.
    @param speed number|nil
        Optional interpolation speed. Uses Config.AnimationSpeed when omitted.
    @return number
        Smoothed animation value.
]]
---@param id string
---@param target number
---@param speed number|nil
---@return number
function DXForge:Animate(id, target, speed)
    local current = self.Animations[id]
    if current == nil then current = target end
    local delta = self.Runtime.Delta > 0 and self.Runtime.Delta or 1 / 60
    current = lerp(current, target, 1 - math.exp(-(speed or self.Config.AnimationSpeed) * delta))
    self.Animations[id] = current
    return current
end

--[[
    Returns a looping 0..1 pulse value.

    @param speed number|nil
        Pulse speed multiplier.
    @return number
        Current pulse value between 0 and 1.
]]
---@param speed number|nil
---@return number
function DXForge:Pulse(speed)
    return (math.sin((os.clock() - self.Runtime.StartedAt) * (speed or 3)) + 1) / 2
end

